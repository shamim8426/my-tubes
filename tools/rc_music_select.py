"""Scene-based music selector (all channels): cue sheet (mood per section) + shared/music/mood_library.json -> music plan for tools/rc_music_mix.py.
python tools/rc_music_select.py <story> --sheet long/mood_cue_sheet.json [--out long/music_cues_mood.json]
Cue sheet: {"sections": [{"line": 1, "mood": "curious_mystery", "why": "..."}, ...], "pivot_lines": [5, 34, ...]}
Rules: one track per section, never the same track twice in a row (and prefer unused tracks); cue changes only at section boundaries:
0.75 s before the section's first line with a 5 s equal-power crossfade, or inside the music-off hold when the section follows a pivot
line (hold = pivot line start - 0.3 s .. next line start; cosine ramp 2.5 s down / 3 s up in the mixer) with a sub boom at the new
section start. Levels: per-mood gain on top of the speaker-band calibration (music 10-13 LU under the voice in 150 Hz-8 kHz)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOOD_GAIN = {"curious_mystery": 0.0, "calm_wonder": 0.0, "rising_tension": 1.0, "danger_dark": 1.5, "loss_somber": -1.0, "hope_recovery": 0.5,
             "time_night": 0.0, "reflective_serious": -1.0, "discovery_awe": 1.0, "ending_resolution": 2.0}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("story")
    ap.add_argument("--sheet", required=True)
    ap.add_argument("--out", default="long/music_cues_mood.json")
    ap.add_argument("--xf", type=float, default=6.0)
    ap.add_argument("--channel", default="reality-check")
    a = ap.parse_args()
    sd = next((ROOT / "channels" / a.channel / "stories").glob(f"{a.story}_*"))
    lines = json.loads((sd / "audio/voiceover_timing.json").read_text(encoding="utf-8"))
    by = {l["line"]: l for l in lines}
    sheet = json.loads((sd / a.sheet).read_text(encoding="utf-8"))
    lib = json.loads((ROOT / "shared/music/mood_library.json").read_text(encoding="utf-8"))
    pivots = sorted(sheet.get("pivot_lines", []))
    holds = {}
    for p in pivots:
        nxt = by.get(p + 1)
        if nxt:
            holds[p] = [round(by[p]["start"] - 0.3, 2), round(nxt["start"], 2)]
    secs = sorted(sheet["sections"], key=lambda s: s["line"])
    total = lines[-1]["end"] + 8.0
    used, prev, cues, booms, rows = {}, None, [], [], []
    for i, s in enumerate(secs):
        L = s["line"]
        end_t = by[secs[i + 1]["line"]]["start"] if i + 1 < len(secs) else total
        after_pivot = (L - 1) in holds
        if i == 0:
            t, xf = 0.0, a.xf
        elif after_pivot:
            h0, h1 = holds[L - 1]
            t, xf = round(h0 + 0.3, 2), round(max(4.0, min(a.xf, h1 - h0 - 0.6)), 2)   # never shorter than 4 s (user 2026-11-15: no sudden change)
            booms.append({"t": by[L]["start"], "rel": -6.0, "why": f"section start L{L} after pivot L{L - 1}"})
        else:
            t, xf = round(by[L]["start"] - 0.75, 2), a.xf
        need = end_t - t + xf
        cands = [r for r in lib["moods"][s["mood"]] if r["path"] != prev and not r.get("default_bed")]
        if not cands:
            raise SystemExit(f"no usable track for mood {s['mood']}")
        cands.sort(key=lambda r: (used.get(r["path"], 0.0) > 0, -(2 * r["mid_share_150_2k"] - r["beat_strength"] + min(r["length_s"], 600) / 600)))
        r = cands[0]
        off = r["usable_start_s"] + used.get(r["path"], 0.0)
        if off + need > r["loop_end_s"]:
            off = r["usable_start_s"]
        used[r["path"]] = used.get(r["path"], 0.0) + need
        cues.append({"t": t, "track": r["path"], "off": round(off, 1), "name": f"{s['mood']}: {r['title']}", "gain_db": MOOD_GAIN.get(s["mood"], 0.0), "xf": xf,
                     "hi": None})
        rows.append((t, L, s["mood"], r["title"], r["licence"], s.get("why", "")))
        prev = r["path"]
    for c in cues:
        c.pop("hi")
    cfg = {"_note": f"generated by tools/rc_music_select.py from {a.sheet}", "xf": a.xf, "cues": cues, "off_windows": [holds[p] for p in pivots if p in holds],
           "booms": booms, "event_types": [], "band_cal": True, "mid_eq": True, "sub_cut_db": 9.0, "mid_boost_db": 6.0,
           "off_depth_db": 18.0, "off_down": 5.0, "off_up": 5.5, "max_db_per_s": 6.0,   # gradual: cosine 18 dB over 5 s peaks ~5.7 dB/s "big_gap_db": 3.5, "mid_gap_db": 2.0, "big_gap_min": 0.6,
           "section_swell_db": 1.0, "fade_in": 6.0, "fade_out": 12.0, "end_swell_db": 3.0, "lev_max_down": 10.0, "lev_max_up": 10.0,
           "credits": sorted({next(r["credit"] for m in lib["moods"].values() for r in m if r["path"] == c["track"]) for c in cues})}
    (sd / a.out).write_text(json.dumps(cfg, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{'time':>7s} {'line':>4s}  {'mood':18s} track")
    for t, L, m, ti, li, why in rows:
        print(f"{int(t // 60)}:{t % 60:05.2f} L{L:<4d} {m:18s} {ti} ({li})  {why}")
    print("off windows:", cfg["off_windows"])
    print("wrote", sd / a.out)


if __name__ == "__main__":
    main()
